#!/usr/bin/env python3
"""Builds public/content.js and public/bible/*.json from the curriculum and the BSB text.

Usage: python3 build/build.py path/to/BSB.json
BSB.json: https://raw.githubusercontent.com/scrollmapper/bible_databases/master/formats/json/BSB.json
The Berean Standard Bible is in the public domain.
"""
import json, re, sys, os, importlib.util

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PUBLIC = os.path.join(ROOT, "public")
CUR = os.path.join(ROOT, "build", "curriculum")
ORDER = ["journey", "old_testament", "new_testament", "gospels", "stories"]

ROMAN = {"1": "I", "2": "II", "3": "III"}
DISPLAY = {"Revelation of John": "Revelation", "Song of Solomon": "Song of Songs"}


def tidy(t):
    """Swap em dashes for commas (or drop them next to other punctuation). Words are untouched."""
    def dash(m):
        before = t[:m.start()].rstrip()
        after = t[m.end():].lstrip()
        if not before or not after:
            return ""
        if before[-1] in ",.;:!?“‘(" or after[0] in ",.;:!?”’)":
            return "" if after[0] in ",.;:!?”’)" else " "
        return ", "
    t = re.sub(r"\s*—\s*", dash, t)
    return re.sub(r"\s{2,}", " ", t).strip()


SUPERSCRIPT = re.compile(r"^((?:[^.]{0,80}\b(?:Psalm|psalm|choirmaster|David|Korah|Asaph|Maskil|Miktam|song|Song|Alamoth|Shiggaion|Solomon|Moses)\b[^.]{0,80}\.\s*)+)")


def strip_superscription(text):
    m = SUPERSCRIPT.match(text)
    return text[m.end():] if m and len(text) - m.end() > 10 else text


def load_bible(path):
    d = json.load(open(path))
    books = d["books"]
    assert len(books) == 66
    return books


def display_name(src):
    if src in DISPLAY:
        return DISPLAY[src]
    m = re.match(r"^(I{1,3}) (.+)$", src)
    if m:
        return {"I": "1", "II": "2", "III": "3"}[m.group(1)] + " " + m.group(2)
    return src


def main(bsb_path):
    books = load_bible(bsb_path)
    names = [display_name(b["name"]) for b in books]
    index = {n: i for i, n in enumerate(names)}
    index["Psalm"] = index["Psalms"]

    # Per-book files for the in-app Bible reader
    os.makedirs(os.path.join(PUBLIC, "bible"), exist_ok=True)
    for i, b in enumerate(books):
        chapters = [[tidy(v["text"]) for v in c["verses"]] for c in b["chapters"]]
        json.dump({"name": names[i], "chapters": chapters}, open(os.path.join(PUBLIC, "bible", f"{i}.json"), "w"), ensure_ascii=False, separators=(",", ":"))

    def resolve(ref):
        m = re.match(r"^(.+?) (\d+):(\d+)(?:-(\d+))?$", ref.strip())
        if not m:
            raise SystemExit("Bad reference: " + ref)
        book, ch, v1, v2 = m.group(1), int(m.group(2)), int(m.group(3)), m.group(4)
        v2 = int(v2) if v2 else v1
        if book not in index:
            raise SystemExit("Unknown book in: " + ref)
        bi = index[book]
        chap = books[bi]["chapters"][ch - 1]["verses"]
        if v2 > len(chap) or v1 < 1 or v2 < v1:
            raise SystemExit("Verse out of range: " + ref)
        shown = ("Psalm" if names[bi] == "Psalms" else names[bi]) + f" {ch}:{v1}" + (f"-{v2}" if v2 != v1 else "")
        vs = [[n, tidy(chap[n - 1]["text"])] for n in range(v1, v2 + 1)]
        if names[bi] == "Psalms" and v1 == 1:
            vs[0][1] = strip_superscription(vs[0][1])
        return shown, {"b": bi, "c": ch, "v": vs}

    verses, sections, n_lessons = {}, [], 0
    for mod in ORDER:
        spec = importlib.util.spec_from_file_location(mod, os.path.join(CUR, mod + ".py"))
        m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
        S = m.SECTION
        units = []
        for ui, (ut, ud, lessons) in enumerate(S["units"]):
            L = []
            for li, (title, refs, teach, qs) in enumerate(lessons):
                keys = []
                for r in refs.split(";"):
                    k, data = resolve(r)
                    verses[k] = data; keys.append(k)
                for q in qs:
                    assert len(q) >= 3 and len(set(q[1:])) == len(q) - 1, (title, q)
                L.append({"id": f"{S['id']}-{ui}-{li}", "t": title,
                          "teach": [p.strip() for p in teach.split("|")],
                          "v": keys, "q": [list(q) for q in qs]})
                n_lessons += 1
            units.append({"t": ut, "d": ud, "lessons": L})
        sections.append({"id": S["id"], "name": S["name"], "color": S["color"], "desc": S["desc"], "units": units})

    meta = [{"name": names[i], "ch": len(b["chapters"])} for i, b in enumerate(books)]
    out = ("// Generated by build/build.py. Do not edit by hand; edit build/curriculum/*.py and rebuild.\n"
           "// Scripture: Berean Standard Bible (BSB), public domain.\n"
           f"export const SECTIONS={json.dumps(sections, ensure_ascii=False, separators=(',', ':'))};\n"
           f"export const VERSES={json.dumps(verses, ensure_ascii=False, separators=(',', ':'))};\n"
           f"export const BOOKS={json.dumps(meta, ensure_ascii=False, separators=(',', ':'))};\n")
    open(os.path.join(PUBLIC, "content.js"), "w").write(out)
    print(f"{len(sections)} sections, {n_lessons} lessons, {len(verses)} passages, content.js {len(out)//1024} KB")


if __name__ == "__main__":
    main(sys.argv[1])
